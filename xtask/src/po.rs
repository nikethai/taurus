//! A small gettext catalog reader and writer: just what the Slint extractor
//! produces (`msgctxt`, `msgid`, `msgid_plural`, `msgstr`, `msgstr[N]`,
//! continued strings, comments). Strings stay escaped as in the file, so
//! they are written back exactly as they were read.
//!
//! The parser is copied into apps/taurus-desktop/tests/common/po.rs; keep
//! the two in step.

use std::fmt::Write;

/// One message of the catalog (the header, whose id is empty, is left out).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Entry {
    pub ctxt: Option<String>,
    pub id: String,
    pub plural: Option<String>,
}

#[derive(Clone, Copy)]
enum Field {
    Ctxt,
    Id,
    Plural,
    Str(usize),
}

#[derive(Default)]
struct Raw {
    ctxt: Option<String>,
    id: Option<String>,
    plural: Option<String>,
    strs: Vec<String>,
}

impl Raw {
    fn slot(&mut self, field: Field) -> &mut String {
        match field {
            Field::Ctxt => self.ctxt.get_or_insert_default(),
            Field::Id => self.id.get_or_insert_default(),
            Field::Plural => self.plural.get_or_insert_default(),
            Field::Str(i) => {
                if self.strs.len() <= i {
                    self.strs.resize(i + 1, String::new());
                }
                &mut self.strs[i]
            }
        }
    }

    fn flush(&mut self, out: &mut Vec<(Entry, Vec<String>)>) {
        let raw = std::mem::take(self);
        if let Some(id) = raw.id.filter(|id| !id.is_empty()) {
            let (ctxt, plural) = (raw.ctxt, raw.plural);
            out.push((Entry { ctxt, id, plural }, raw.strs));
        }
    }
}

/// Every message with its `msgstr`s (one, or one per plural form).
pub fn parse(text: &str) -> Vec<(Entry, Vec<String>)> {
    let mut out = Vec::new();
    let mut raw = Raw::default();
    let mut last = Field::Id;
    for line in text.lines().map(str::trim) {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line.starts_with('"') {
            raw.slot(last).push_str(unquote(line));
            continue;
        }
        let (key, value) = line.split_once(' ').unwrap_or((line, ""));
        let field = match key {
            "msgctxt" => Field::Ctxt,
            "msgid" => Field::Id,
            "msgid_plural" => Field::Plural,
            "msgstr" => Field::Str(0),
            _ => match key
                .strip_prefix("msgstr[")
                .and_then(|k| k.strip_suffix(']'))
            {
                Some(n) => Field::Str(n.parse().unwrap_or(0)),
                None => continue,
            },
        };
        let starts_entry = matches!(field, Field::Ctxt)
            || (matches!(field, Field::Id) && (raw.id.is_some() || !raw.strs.is_empty()));
        if starts_entry {
            raw.flush(&mut out);
        }
        raw.slot(field).push_str(unquote(value.trim()));
        last = field;
    }
    raw.flush(&mut out);
    out
}

fn unquote(s: &str) -> &str {
    let s = s.strip_prefix('"').unwrap_or(s);
    s.strip_suffix('"').unwrap_or(s)
}

/// The messages of a `.pot` (or `.po`), in file order.
pub fn parse_pot(text: &str) -> Vec<Entry> {
    parse(text).into_iter().map(|(entry, _)| entry).collect()
}

/// A catalog for `lang` with `translate` applied to each source string
/// (`msgid`, and `msgid_plural` for the second plural form). No dates or
/// file references, so it changes only when the strings do.
pub fn write_po(entries: &[Entry], lang: &str, translate: impl Fn(&str) -> String) -> String {
    let mut out = String::new();
    out.push_str("# Generated by `cargo xtask i18n pseudo` from taurus-desktop.pot.\n");
    out.push_str("# Do not edit: run that command again instead.\n");
    out.push_str("msgid \"\"\nmsgstr \"\"\n");
    let _ = writeln!(out, "\"Language: {lang}\\n\"");
    out.push_str("\"MIME-Version: 1.0\\n\"\n");
    out.push_str("\"Content-Type: text/plain; charset=UTF-8\\n\"\n");
    out.push_str("\"Content-Transfer-Encoding: 8bit\\n\"\n");
    out.push_str("\"Plural-Forms: nplurals=2; plural=(n != 1);\\n\"\n");
    for e in entries {
        out.push('\n');
        if let Some(ctxt) = &e.ctxt {
            let _ = writeln!(out, "msgctxt \"{ctxt}\"");
        }
        let _ = writeln!(out, "msgid \"{}\"", e.id);
        match &e.plural {
            Some(plural) => {
                let _ = writeln!(out, "msgid_plural \"{plural}\"");
                let _ = writeln!(out, "msgstr[0] \"{}\"", translate(&e.id));
                let _ = writeln!(out, "msgstr[1] \"{}\"", translate(plural));
            }
            None => {
                let _ = writeln!(out, "msgstr \"{}\"", translate(&e.id));
            }
        }
    }
    out
}

/// The pseudo-locale form of an (escaped) source string: accented letters,
/// padded to at least 1.4 times the length with `·`, wrapped in `⟦…⟧`.
/// Placeholders (`{0}`, `{n}`, `{}`), escapes such as `\n`, and the product
/// name `Hyades` pass through untouched.
pub fn pseudo(s: &str) -> String {
    let mut body = String::new();
    let mut rest = s;
    while let Some(c) = rest.chars().next() {
        let keep = kept_len(rest);
        if keep > 0 {
            body.push_str(&rest[..keep]);
            rest = &rest[keep..];
        } else {
            body.push(accent(c));
            rest = &rest[c.len_utf8()..];
        }
    }
    let want = (s.chars().count() * 14).div_ceil(10);
    let have = body.chars().count();
    body.extend(std::iter::repeat_n('·', want.saturating_sub(have)));
    format!("⟦{body}⟧")
}

/// Bytes at the start of `s` that `pseudo` copies as they are.
fn kept_len(s: &str) -> usize {
    if s.starts_with("Hyades") {
        return "Hyades".len();
    }
    if let Some(escaped) = s.strip_prefix('\\') {
        return 1 + escaped.chars().next().map_or(0, char::len_utf8);
    }
    if let Some((name, _)) = s.strip_prefix('{').and_then(|r| r.split_once('}'))
        && (name.is_empty() || name == "n" || name.bytes().all(|b| b.is_ascii_digit()))
    {
        return name.len() + 2;
    }
    0
}

fn accent(c: char) -> char {
    match c {
        'a' => 'á',
        'e' => 'é',
        'i' => 'í',
        'o' => 'ó',
        'u' => 'ú',
        'y' => 'ý',
        'c' => 'ç',
        'n' => 'ñ',
        'A' => 'Á',
        'E' => 'É',
        'I' => 'Í',
        'O' => 'Ó',
        'U' => 'Ú',
        'Y' => 'Ý',
        'C' => 'Ç',
        'N' => 'Ñ',
        other => other,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pseudo_keeps_placeholders_and_name() {
        let p = pseudo("Open Hyades {0} of {n}");
        assert!(p.starts_with('⟦') && p.ends_with('⟧'));
        for keep in ["Hyades", "{0}", "{n}"] {
            assert!(p.contains(keep), "{p}");
        }
        assert!(p.contains("Ópéñ"), "{p}");
    }

    #[test]
    // The bound is spelled as in the task brief.
    #[allow(clippy::manual_div_ceil)]
    fn pseudo_is_at_least_forty_percent_longer() {
        let s = "Pause all";
        assert!(pseudo(s).chars().count() >= (s.chars().count() * 14 + 9) / 10 + 2);
    }

    #[test]
    fn parse_and_write_round_trip_plurals_and_context() {
        let pot = "msgctxt \"Row\"\nmsgid \"{n} file\"\nmsgid_plural \"{n} files\"\nmsgstr[0] \"\"\nmsgstr[1] \"\"\n";
        let e = parse_pot(pot);
        assert_eq!(e[0].ctxt.as_deref(), Some("Row"));
        let po = write_po(&e, "en_XA", pseudo);
        assert!(po.contains("msgstr[1] \"⟦{n} fílés"));
    }
}
